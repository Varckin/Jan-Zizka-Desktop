export function createMenuLink(action, label, iconName, danger = false) {
    const link = document.createElement('a');
    link.dataset.action = action;
    if (danger) link.classList.add('is-danger');
    const icon = document.createElement('span');
    icon.className = 'menu-icon';
    icon.innerHTML = MENU_ICONS[iconName] || '';
    const text = document.createElement('span');
    text.className = 'menu-label';
    text.textContent = label;
    link.appendChild(icon);
    link.appendChild(text);
    return link;
}

export function updateMenuLink(link, label, iconName) {
    if (!link) return;
    const text = link.querySelector('.menu-label');
    if (text) text.textContent = label;
    else link.textContent = label;
    if (iconName) {
        const icon = link.querySelector('.menu-icon');
        if (icon) icon.innerHTML = MENU_ICONS[iconName] || '';
    }
}
